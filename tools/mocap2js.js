// data/mocap/turn_cycle_*.json -> src/06b_mocapdata.js: the channels the skier is driven by, one right turn of 32 phases each
// (run after the cycles change: node tools/mocap2js.js). Credits and licences: data/mocap/CREDITS.md
const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
const r3 = a => a.map(v => Math.round(v * 1000) / 1000);
const pick = (f) => {
  const d = JSON.parse(fs.readFileSync(path.join(root, 'data/mocap', f), 'utf8')), J = d.joints, c = i => k => r3(J[k].map(p => p[i]));
  return { T: d.meta.turn_seconds_median, credit: d.meta.credit, inc: r3(d.inclination), hip: r3(d.hipHeight), twist: r3(d.twist),
    lwx: c(0)('l_wrist'), lwy: c(1)('l_wrist'), lwz: c(2)('l_wrist'), rwx: c(0)('r_wrist'), rwy: c(1)('r_wrist'), rwz: c(2)('r_wrist') };
};
const out = { cc: pick('turn_cycle_cc.json') };
fs.writeFileSync(path.join(root, 'src/06b_mocapdata.js'), '// generated by tools/mocap2js.js from data/mocap/ (see data/mocap/CREDITS.md). Do not edit by hand\nconst MOCAP_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote src/06b_mocapdata.js');
