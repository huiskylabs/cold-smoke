// One-off: downloads the three title/interface faces the web page fetches from Google Fonts into xhs/fonts/, for the 小红书 小工具
// package (the container cannot reach the network). Latin subsets only for Jost and Cormorant Garamond; Noto Serif SC is cut to the
// same characters the web page asks for. Writes xhs/fonts/fonts.css. All three are SIL Open Font License.
// Run: node tools/fetch-xhs-fonts.js   (needs network; the results are committed, the build does not need it)
const fs = require('fs'), path = require('path');
const out = path.join(__dirname, '..', 'xhs', 'fonts'); fs.mkdirSync(out, { recursive: true });
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const tpl = fs.readFileSync(path.join(__dirname, '..', 'template.html'), 'utf8');
const SONG = /text=' \+ encodeURIComponent\('([^']+)'\)/.exec(tpl)[1];
const fams = [
  { url: 'https://fonts.googleapis.com/css2?family=Jost:wght@300;400;500&display=swap', subset: 'latin' },
  { url: 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@300;500;700&display=swap', subset: 'latin' },
  { url: 'https://fonts.googleapis.com/css2?family=Noto+Serif+SC:wght@300;500;700&display=swap&text=' + encodeURIComponent(SONG), subset: null },
];
(async () => {
  let css = '/* generated by tools/fetch-xhs-fonts.js: SIL Open Font License faces from Google Fonts, kept in the package */\n';
  for (const n of fs.readdirSync(out)) fs.unlinkSync(path.join(out, n));
  for (const f of fams) {
    const seen = {};      // (Google serves one variable file for all the weights: kept once, declared for the whole range)
    const txt = await (await fetch(f.url, { headers: { 'user-agent': UA } })).text();
    const blocks = txt.split('@font-face').slice(1).map((b, i, a) => ({ b, label: (txt.split('@font-face')[i].match(/\/\* ([\w-]+) \*\/\s*$/) || [])[1] }));
    for (const { b, label } of blocks) {
      if (f.subset && label !== f.subset) continue;
      const fam = /font-family: '([^']+)'/.exec(b)[1], w = /font-weight: (\d+)/.exec(b)[1], src = /url\(([^)]+)\)/.exec(b)[1];
      if (seen[src]) { seen[src].w.push(+w); continue; }
      const name = fam.replace(/\s+/g, '') + '.woff2';
      const buf = Buffer.from(await (await fetch(src, { headers: { 'user-agent': UA } })).arrayBuffer());
      fs.writeFileSync(path.join(out, name), buf);
      const ur = /unicode-range: ([^;]+);/.exec(b);
      seen[src] = { fam, name, w: [+w], ur: ur ? ur[1] : null };
      console.log(name, buf.length);
    }
    for (const e of Object.values(seen)) css += `@font-face { font-family: '${e.fam}'; font-style: normal; font-weight: ${Math.min(...e.w)} ${Math.max(...e.w)}; font-display: swap; src: url(./${e.name}) format('woff2');${e.ur ? ' unicode-range: ' + e.ur + ';' : ''} }\n`;
  }
  fs.writeFileSync(path.join(out, 'fonts.css'), css);
})();
