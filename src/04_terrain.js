  let R: f32 = texLod(tTrk, (xz + U.origin.xz) / 12.8, 1.0 + smoothstep(0.02, 0.05, M.pk.z)).x * smoothstep(mix(2.75, 2.95, M.tb.w), mix(2.25, 2.5, M.tb.w), length(xz - M.pk.xy)) * M.pk.w;
