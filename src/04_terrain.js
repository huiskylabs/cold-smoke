// ---------------------------------------------------------------- terrain: CPU height function -> toroidal clipmap textures -> nested grid rings
const Tex = {};      // shared procedural textures (generated by code at boot)

function makeNoiseTextures(gfx) {
  // tNoise: 256^2 white noise; G = R shifted by (37,17) so one bilinear fetch yields two z-slices of 3D value noise
  { const n = 256, d = new Uint8Array(n * n * 4), r = new Uint8Array(n * n), b = new Uint8Array(n * n);
    for (let i = 0; i < n * n; i++) { r[i] = hashU(i * 2 + 1) >>> 24; b[i] = hashU(i * 2 + 0x9e3779) >>> 24; }
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) { const i = y * n + x, j = ((y + 17) & 255) * n + ((x + 37) & 255); d[i * 4] = r[i]; d[i * 4 + 1] = r[j]; d[i * 4 + 2] = b[i]; d[i * 4 + 3] = b[j]; }
    Tex.noise = gfx.texture({ w: n, h: n, format: 'rgba8', wrap: 'repeat', filter: 'linear', data: d }); }
  Tex.black = gfx.texture({ w: 1, h: 1, format: 'rgba8', wrap: 'clamp', filter: 'linear', data: new Uint8Array([0, 0, 0, 0]) });
  // tDetail: 512^2 tiling fbm height (B) with its slopes (R,G) and per-texel white noise (A); mipmapped
  { const n = 512, h = new Float32Array(n * n), d = new Uint8Array(n * n * 4);
    const oct = [[6, 1.0], [12, 0.5], [24, 0.27], [48, 0.15], [96, 0.085], [192, 0.05]];
    for (let o = 0; o < oct.length; o++) {
      const P = oct[o][0], amp = oct[o][1], lat = new Float32Array(P * P); for (let i = 0; i < P * P; i++) lat[i] = hash2(i, 977 + o) * 2 - 1;
      for (let y = 0; y < n; y++) { const fy = y * P / n, iy = Math.floor(fy), ty = fy - iy, uy = ty * ty * ty * (ty * (ty * 6 - 15) + 10), y0 = (iy % P) * P, y1 = ((iy + 1) % P) * P;
        for (let x = 0; x < n; x++) { const fx = x * P / n, ix = Math.floor(fx), tx = fx - ix, ux = tx * tx * tx * (tx * (tx * 6 - 15) + 10), x0 = ix % P, x1 = (ix + 1) % P;
          h[y * n + x] += amp * lerp(lerp(lat[y0 + x0], lat[y0 + x1], ux), lerp(lat[y1 + x0], lat[y1 + x1], ux), uy); } }
    }
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const i = y * n + x, gx = (h[y * n + ((x + 1) & 511)] - h[y * n + ((x + 511) & 511)]) * 0.5 * n / 48, gy = (h[((y + 1) & 511) * n + x] - h[((y + 511) & 511) * n + x]) * 0.5 * n / 48;
      d[i * 4] = clamp(128 + gx * 127, 0, 255); d[i * 4 + 1] = clamp(128 + gy * 127, 0, 255); d[i * 4 + 2] = clamp(128 + h[i] * 110, 0, 255); d[i * 4 + 3] = hashU(i + 31337) >>> 24;
    }
    Tex.detail = gfx.texture({ w: n, h: n, format: 'rgba8', wrap: 'repeat', filter: 'linear', mips: true, data: d }); gfx.genMips(Tex.detail); }
}

// tSnow / tSnowFine: 512^2 tiling wind-worked snow. B = height, RG = its slopes (signed square root, so gentle drifts keep their precision next to
// steep risers), A = how high the surface ahead rises toward the sun (tangent of the horizon in the sun's direction): the shader compares
// it with the sun's own height to shadow every ripple and slab edge for free.
// Two of them: drifts and wind slab for the large sizes, and the same with wind ripples for the size of a hand. Ripples a metre apart
// would lie across the slope like the rungs of a ladder; real ones are a few fingers apart, wander, fork and die out.
function makeSnowTexture(gfx, sunAz) {
  const n = 512;
  const lat = (P, seed) => { const a = new Float32Array(P * P); for (let i = 0; i < P * P; i++) a[i] = hash2(i, seed) * 2 - 1; return a; };
  const samp = (a, P, u, v) => {
    const fx = u * P, fy = v * P, ix = Math.floor(fx), iy = Math.floor(fy), tx = fx - ix, ty = fy - iy;
    const ux = tx * tx * tx * (tx * (tx * 6 - 15) + 10), uy = ty * ty * ty * (ty * (ty * 6 - 15) + 10);
    const x0 = ((ix % P) + P) % P, x1 = (x0 + 1) % P, y0 = (((iy % P) + P) % P) * P, y1 = ((((iy + 1) % P) + P) % P) * P;
    return lerp(lerp(a[y0 + x0], a[y0 + x1], ux), lerp(a[y1 + x0], a[y1 + x1], ux), uy);
  };
  const mk = (list, seed) => list.map(([P, amp], i) => ({ P, amp, a: lat(P, seed + i) }));
  const fb = (L, u, v) => { let s = 0; for (const o of L) s += o.amp * samp(o.a, o.P, u, v); return s; };
  const sx = Math.sin(sunAz), sy = -Math.cos(sunAz), steps = [1, 2, 3, 4, 5, 7, 9, 12, 16, 21, 27, 34, 42, 52];
  const enc = g => { const q = clamp(g / 48, -1, 1); return clamp(127.5 + 127.5 * Math.sign(q) * Math.sqrt(Math.abs(q)), 0, 255); };
  const build = (ripples, seed) => {
    const h = new Float32Array(n * n), d = new Uint8Array(n * n * 4);
    const Lb = mk([[3, 1], [6, 0.5], [12, 0.25], [24, 0.12]], seed), Lw1 = mk([[3, 1], [6, 0.5], [12, 0.25]], seed + 100), Lw2 = mk([[4, 1], [8, 0.5]], seed + 200);
    const Lm = mk([[4, 1], [8, 0.5]], seed + 300), Lg = mk([[64, 1], [128, 0.6], [256, 0.35]], seed + 400), Lw3 = mk([[10, 1], [20, 0.5]], seed + 500), La = mk([[9, 1], [18, 0.6]], seed + 600);
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const u = x / n, v = y / n, b = fb(Lb, u, v) / 1.87;
      // wind slab: terraces along the contours of the drift, flat tread and a short steep riser
      const t = b * 1.7 + 8, ft = Math.floor(t), fr = t - ft, terr = (ft - 8 + smooth(0, 0.17, fr)) / 1.7;
      let hh = 0.50 * terr + 0.22 * b + 0.045 * fb(Lg, u, v) / 1.95;
      if (ripples) {
        // wind ripples: a sawtooth, steep on the lee side. The crests wander (two sizes of warp), so they close up, open out and fork;
        // their height comes and goes along each crest, and whole patches of the slope have none
        const w1 = fb(Lw1, u, v), w2 = fb(Lw2, u, v), w3 = fb(Lw3, u, v);
        const ph = v * 19 + u * 4 + w1 * 2.2 + w3 * 0.55, saw = ph - Math.floor(ph), rip = saw < 0.72 ? saw / 0.72 : 1 - (saw - 0.72) / 0.28;
        const mask = smooth(-0.25, 0.35, fb(Lm, u + w2 * 0.03, v) / 1.5) * (0.45 + 0.55 * smooth(-0.5, 0.4, fb(La, u, v) / 1.6));
        hh += 0.17 * (rip * rip * (3 - 2 * rip) - 0.5) * mask;
      }
      h[y * n + x] = hh;
    }
    const H = (x, y) => h[(y & 511) * n + (x & 511)];
    const Hb = (x, y) => { const ix = Math.floor(x), iy = Math.floor(y), tx = x - ix, ty = y - iy; return lerp(lerp(H(ix, iy), H(ix + 1, iy), tx), lerp(H(ix, iy + 1), H(ix + 1, iy + 1), tx), ty); };
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const i = y * n + x, h0 = h[i];
      let hz = 0; for (const st of steps) { const q = (Hb(x + sx * st, y + sy * st) - h0) / st * n; if (q > hz) hz = q; }
      d[i * 4] = enc((H(x + 1, y) - H(x - 1, y)) * 0.5 * n); d[i * 4 + 1] = enc((H(x, y + 1) - H(x, y - 1)) * 0.5 * n);
      d[i * 4 + 2] = clamp(127.5 + h0 * 110, 0, 255); d[i * 4 + 3] = clamp(hz / 48 * 255, 0, 255);
    }
    const t = gfx.texture({ w: n, h: n, format: 'rgba8', wrap: 'repeat', filter: 'linear', mips: true, data: d }); gfx.genMips(t); return t;
  };
  Tex.snow = build(false, 2100); Tex.snowFine = build(true, 2100);
}

const Terrain = (() => {
  const T = { LEVELS: 8, N: 256, G: 128, BIAS: 24, levels: [], ready: false, sheen: 0.55 };
  const N = T.N, G = T.G;
  let gfx, vb, ibFull, ibRing = {}, pipe, pipeShadow, cntFull, cntRing;
  const tmpH = new Float32Array(N * N), tmpN = new Uint16Array(N * N * 4), tmpS = new Uint16Array(N * N * 4);
  let sunX = 0, sunZ = -1;
  // the sun keeps its compass bearing all day (only its height changes), so the horizon toward it can be worked out once per texel
  T.setSun = function (az) { sunX = Math.sin(az); sunZ = -Math.cos(az); };
  const hzOut = [0, 0];
  // how high the mountain rises toward the sun as seen from (x, z, h0): tangent of that horizon, and 1/distance to the crest that makes it.
  // Walks outward in growing steps, reading each distance from the finest clipmap level that still resolves it.
  function horizon(L, x, z, h0) {
    let hz = -1, inv = 0, d = L.cell * 1.5;
    for (let k = 0; k < 44 && d < 9000; k++, d *= 1.3) {
      const sx = x + sunX * d, sz = z + sunZ * d;
      let m = Math.max(L.l, Math.min(T.LEVELS - 1, Math.floor(Math.log2(d / 3))));
      for (; m < T.LEVELS; m++) {
        const Lm = T.levels[m]; if (!Lm.valid) continue;
        const gx = Math.round(sx / Lm.cell), gz = Math.round(sz / Lm.cell);
        if (gx < Lm.cx - 128 || gx > Lm.cx + 127 || gz < Lm.cz - 128 || gz > Lm.cz + 127) continue;
        const t = (Lm.H[texelIndex(gx, gz)] + HREF_SLOPE * gz * Lm.cell - h0) / d;
        if (t > hz) { hz = t; inv = 1 / d; }
        break;
      }
      if (m >= T.LEVELS) break;
    }
    hzOut[0] = hz; hzOut[1] = inv;
  }
  // height (minus the reference plane) read from a level's own grid, between its cells
  function bil(Lm, x, z) {
    const fx = x / Lm.cell, fz = z / Lm.cell, ix = Math.floor(fx), iz = Math.floor(fz), tx = fx - ix, tz = fz - iz, Hm = Lm.H;
    const x0 = clamp(ix, Lm.cx - 128, Lm.cx + 127), x1 = clamp(ix + 1, Lm.cx - 128, Lm.cx + 127), z0 = clamp(iz, Lm.cz - 128, Lm.cz + 127), z1 = clamp(iz + 1, Lm.cz - 128, Lm.cz + 127);
    return lerp(lerp(Hm[texelIndex(x0, z0)], Hm[texelIndex(x1, z0)], tx), lerp(Hm[texelIndex(x0, z1)], Hm[texelIndex(x1, z1)], tx), tz);
  }
  const tn = { ok: false, x: 0, z: 0, h: 0, r: 0, d: 0 };

  T.init = function (g) {
    gfx = g;
    for (let l = 0; l < T.LEVELS; l++) {
      T.levels.push({ l, cell: 0.5 * (1 << l), H: new Float32Array(N * N), cx: 0, cz: 0, valid: false,
        hTex: gfx.texture({ w: N, h: N, format: 'r32f', filter: 'nearest', wrap: 'repeat' }),
        nTex: gfx.texture({ w: N, h: N, format: 'rgba16f', filter: 'linear', wrap: 'repeat' }),
        sTex: gfx.texture({ w: N, h: N, format: 'rgba16f', filter: 'linear', wrap: 'repeat' }) });
    }
    const v = new Float32Array((G + 1) * (G + 1) * 2); let k = 0;
    for (let j = 0; j <= G; j++) for (let i = 0; i <= G; i++) { v[k++] = i; v[k++] = j; }
    vb = gfx.buffer(v, 'vertex');
    const mk = (hx0, hx1, hz0, hz1) => {
      const idx = [];
      for (let j = 0; j < G; j++) for (let i = 0; i < G; i++) {
        if (i >= hx0 && i < hx1 && j >= hz0 && j < hz1) continue;
        const a = j * (G + 1) + i; idx.push(a, a + G + 1, a + 1, a + 1, a + G + 1, a + G + 2);
      }
      return { ib: gfx.buffer(new Uint32Array(idx), 'index'), n: idx.length };
    };
    const f = mk(0, 0, 0, 0); ibFull = f.ib; cntFull = f.n;
    for (let ox = 0; ox < 2; ox++) for (let oz = 0; oz < 2; oz++) { const r = mk(32 + ox, 96 + ox, 32 + 12 + oz, 96 + 12 + oz); ibRing[ox + ',' + oz] = r; }
    const lib = [SL.common, SL.hash, SL.fog, SL.shadow, SL.sprayTau, TERRAIN_SSL];
    const desc = {
      name: 'terrain', lib, buffers: [{ attrs: [['ij', 'vec2f']] }],
      varyings: { wp: 'vec3f', uvn: 'vec4f', misc: 'vec4f' },
      uniforms: { lv: 'vec4f', tc: 'vec4f', p: 'vec4f' },
      textures: { tH: 'fetch', tHc: 'fetch', tN: '2d', tNc: '2d', tS: '2d', tSc: '2d', tSnow: '2d', tSnowF: '2d', tNoise: '2d', tDetail: '2d', tShadow: 'shadow', tSky: '2d', tSunTau: '2d', tTrack: '2d' },
      vs: `fn vert(a: VIn) -> VOut { var v: VOut; let t: TerrV = terrainVertex(a.ij); v.wp = t.wp; v.uvn = t.uvn; v.misc = vec4f(t.al, 0.0, 0.0, 0.0); v.clip = U.viewProj * vec4f(t.wp, 1.0); return v; }`,
      fs: TERRAIN_FS.replace(/SUNK/g, (Math.round(9 * sunX / (sunZ || -1)) / 9).toFixed(6)),
    };
    pipe = gfx.pipeline(desc);
    // (into the sun's map the snow goes a little further from the sun than it is: 10 cm, and four texels' worth of its own tilt to the light,
    // which is what a low sun on 6 cm texels needs to keep it from shadowing itself. So the snow asks nothing of what it RECEIVES, and a boot,
    // a hoof, a trunk or a pole shadows it from the point where it stands on it)
    pipeShadow = gfx.pipeline({
      name: 'terrainShadow', lib: [SL.common, TERRAIN_SSL], buffers: [{ attrs: [['ij', 'vec2f']] }], varyings: {}, uniforms: { lv: 'vec4f', tc: 'vec4f', p: 'vec4f' },
      textures: { tH: 'fetch', tHc: 'fetch' }, colorFormat: null, cull: 'none', depthBias: 2, depthBiasSlope: 4.0,
      vs: `fn vert(a: VIn) -> VOut { var v: VOut; let t: TerrV = terrainVertex(a.ij); v.clip = U.shadowVP * vec4f(t.wp - U.sunDir.xyz * 0.10, 1.0); return v; }`, fs: null,
    });
    T.pipes = [pipe, pipeShadow];
  };

  function texelIndex(gx, gz) { return (gz & 255) * N + (gx & 255); }
  // heights for cells [gx0..gx1] x [gz0..gz1] (inclusive) of a level, stored minus the reference plane
  function genHeights(L, gx0, gx1, gz0, gz1) {
    const c = L.cell, H = L.H;
    for (let gz = gz0; gz <= gz1; gz++) { const z = gz * c, row = (gz & 255) * N, ref = HREF_SLOPE * z;
      for (let gx = gx0; gx <= gx1; gx++) H[row + (gx & 255)] = Course.height(gx * c, z, c) - ref; }
  }
  // upload a rect (heights + slopes/masks); neighbours must already be valid in L.H
  function uploadRect(L, gx0, gx1, gz0, gz1) {
    const c = L.cell, H = L.H, wx0 = L.cx - 128, wx1 = L.cx + 127, wz0 = L.cz - 128, wz1 = L.cz + 127;
    gx0 = Math.max(gx0, wx0); gx1 = Math.min(gx1, wx1); gz0 = Math.max(gz0, wz0); gz1 = Math.min(gz1, wz1);
    if (gx1 < gx0 || gz1 < gz0) return;
    // split at the toroidal wrap
    const xs = [], zs = [];
    { let a = gx0; while (a <= gx1) { const b = Math.min(gx1, (a | 255)); xs.push([a, b]); a = b + 1; } }
    { let a = gz0; while (a <= gz1) { const b = Math.min(gz1, (a | 255)); zs.push([a, b]); a = b + 1; } }
    const doAO = L.l <= 2, cvL = T.levels[6], cvB = T.levels[7];
    for (const [za, zb] of zs) for (const [xa, xb] of xs) {
      const w = xb - xa + 1, h = zb - za + 1; let k = 0;
      for (let gz = za; gz <= zb; gz++) for (let gx = xa; gx <= xb; gx++) {
        const i = texelIndex(gx, gz), hc = H[i]; tmpH[k] = hc;
        const xl = gx > wx0 ? H[texelIndex(gx - 1, gz)] : hc, xr = gx < wx1 ? H[texelIndex(gx + 1, gz)] : hc;
        const zl = gz > wz0 ? H[texelIndex(gx, gz - 1)] : hc, zr = gz < wz1 ? H[texelIndex(gx, gz + 1)] : hc;
        const sx = (xr - xl) / (((gx > wx0) + (gx < wx1)) * c || c), sz = (zr - zl) / (((gz > wz0) + (gz < wz1)) * c || c) + HREF_SLOPE;
        const x = gx * c, z = gz * c;
        let ao = 1; const den = Course.treeDensity(x, z);
        if (doAO && den > 0.02) { Course.nearTree(x, z, tn); if (tn.ok) ao = 1 - 0.6 * smooth(tn.r * 2.6, tn.r * 0.5, tn.d); }
        // on the mountain's walls: is this a hollow or a rib, measured across 64 m? Gullies fill with snow and sit in their own shade,
        // crests are blown bare and see the whole sky. It rides in the ambient-light channel (ao - cv / 2).
        const mw = Course.mountain(x, z);
        if (mw > 0.002) {
          let lap;
          if (L.l === 7) lap = 0.6 * (xl + xr + zl + zr - 4 * hc) / 4096;
          else if (L.l === 6) lap = ((gx - 2 >= wx0 ? H[texelIndex(gx - 2, gz)] : hc) + (gx + 2 <= wx1 ? H[texelIndex(gx + 2, gz)] : hc) + (gz - 2 >= wz0 ? H[texelIndex(gx, gz - 2)] : hc) + (gz + 2 <= wz1 ? H[texelIndex(gx, gz + 2)] : hc) - 4 * hc) / 4096;
          else lap = (bil(cvL, x - 64, z) + bil(cvL, x + 64, z) + bil(cvL, x, z - 64) + bil(cvL, x, z + 64) - 4 * bil(cvL, x, z)) / 4096;
          // most of the bend of the mountain's large shapes (the same measure across 192 m) is taken out again: what is left is the gullies
          const big = L.l === 7 ? 0 : (bil(cvB, x - 192, z) + bil(cvB, x + 192, z) + bil(cvB, x, z - 192) + bil(cvB, x, z + 192) - 4 * bil(cvB, x, z)) / 36864;
          ao -= 0.5 * clamp((lap - 0.75 * big) * 22, -0.5, 0.6) * Math.min(1, mw * 4);
        }
        tmpN[k * 4] = toHalf(sx); tmpN[k * 4 + 1] = toHalf(sz); tmpN[k * 4 + 2] = toHalf(ao); tmpN[k * 4 + 3] = toHalf(den);
        horizon(L, x, z, hc + HREF_SLOPE * z);
        tmpS[k * 4] = toHalf(clamp(hzOut[0], -1, 6)); tmpS[k * 4 + 1] = toHalf(hzOut[1]); tmpS[k * 4 + 2] = toHalf(hc); tmpS[k * 4 + 3] = toHalf(mw); k++;
      }
      gfx.updateTexture(L.hTex, xa & 255, za & 255, w, h, tmpH.subarray(0, w * h));
      gfx.updateTexture(L.nTex, xa & 255, za & 255, w, h, tmpN.subarray(0, w * h * 4));
      gfx.updateTexture(L.sTex, xa & 255, za & 255, w, h, tmpS.subarray(0, w * h * 4));
    }
  }
  // returns number of texels generated
  function updateLevel(L, camX, camZ, force) {
    const c = L.cell, tx = Math.floor(camX / (2 * c)) * 2, tz = Math.floor((camZ / c - T.BIAS) / 2) * 2;
    if (!L.valid || force || Math.abs(tx - L.cx) >= 200 || Math.abs(tz - L.cz) >= 200) {
      L.cx = tx; L.cz = tz; L.valid = true; genHeights(L, tx - 128, tx + 127, tz - 128, tz + 127); uploadRect(L, tx - 128, tx + 127, tz - 128, tz + 127); return N * N;
    }
    const dx = tx - L.cx, dz = tz - L.cz; if (!dx && !dz) return 0;
    L.cx = tx; L.cz = tz; let n = 0; const rects = [];
    if (dx > 0) rects.push([tx + 128 - dx, tx + 127, tz - 128, tz + 127]); else if (dx < 0) rects.push([tx - 128, tx - 129 - dx, tz - 128, tz + 127]);
    if (dz > 0) rects.push([tx - 128, tx + 127, tz + 128 - dz, tz + 127]); else if (dz < 0) rects.push([tx - 128, tx + 127, tz - 128, tz - 129 - dz]);
    for (const r of rects) { genHeights(L, r[0], r[1], r[2], r[3]); n += (r[1] - r[0] + 1) * (r[3] - r[2] + 1); }
    const mg = L.l === 6 ? 2 : 1;      // texels this close to the new strip were worked out with a neighbour missing
    for (const r of rects) uploadRect(L, r[0] - mg, r[1] + mg, r[2] - mg, r[3] + mg);
    return n;
  }
  // coarse levels first: the finer ones read them when they look toward the sun
  T.update = function (camX, camZ, force) { let n = 0; for (let l = T.LEVELS - 1; l >= 0; l--) n += updateLevel(T.levels[l], camX, camZ, force); T.lastGen = n; return n; };
  T.updateOne = function (l, camX, camZ) { return updateLevel(T.levels[l], camX, camZ, true); };

  const uni = { lv: [0, 0, 0, 0], tc: [0, 0, 0, 0], p: [0, 0, 0, 0] };
  function setLevelUniforms(L, origin) {
    const c = L.cell, Lc = T.levels[Math.min(T.LEVELS - 1, L.l + 1)], last = L.l === T.LEVELS - 1;
    uni.lv[0] = c; uni.lv[1] = L.cx - origin[0] / c; uni.lv[2] = L.cz - origin[2] / c; uni.lv[3] = last ? 0 : 1;
    uni.tc[0] = L.cx & 255; uni.tc[1] = L.cz & 255; uni.tc[2] = last ? (L.cx & 255) : ((L.cx / 2) & 255); uni.tc[3] = last ? (L.cz & 255) : ((L.cz / 2) & 255);
    uni.p[0] = HREF_SLOPE * origin[2] - origin[1]; uni.p[1] = L.l; uni.p[2] = last ? 1 : 0.5; uni.p[3] = T.sheen;
    return Lc;
  }
  function ringFor(L) {
    if (L.l === 0) return { ib: ibFull, n: cntFull };
    const f = T.levels[L.l - 1], ox = f.cx / 2 - L.cx, oz = f.cz / 2 - L.cz - 12;
    return ibRing[clamp(ox, 0, 1) + ',' + clamp(oz, 0, 1)];
  }
  T.draw = function (origin, shadowTex, skyTex, sunTau) {
    for (const L of T.levels) {
      const Lc = setLevelUniforms(L, origin), r = ringFor(L);
      gfx.draw(pipe, { u: uni, tex: { tH: L.hTex, tHc: Lc.hTex, tN: L.nTex, tNc: Lc.nTex, tS: L.sTex, tSc: Lc.sTex, tSnow: Tex.snow, tSnowF: Tex.snowFine, tNoise: Tex.noise, tDetail: Tex.detail, tShadow: shadowTex, tSky: skyTex, tSunTau: sunTau || Tex.black, tTrack: Tracks.tex }, vb: [vb], ib: r.ib, count: r.n });
    }
  };
  T.drawShadow = function (origin, maxLevel) {
    for (const L of T.levels) {
      if (L.l > maxLevel) break;
      const Lc = setLevelUniforms(L, origin), r = ringFor(L);
      gfx.draw(pipeShadow, { u: uni, tex: { tH: L.hTex, tHc: Lc.hTex }, vb: [vb], ib: r.ib, count: r.n });
    }
  };
  // the same horizon for things that are not terrain (skier, spray, dust, the air): level 3 texture (4 m cells, +-512 m) and its mapping.
  // Its B channel is the ground height (minus the reference plane): ground y in render space = B + HREF_SLOPE * z + xf.w
  T.sunBinding = function (origin, lvl = 3) {
    const L = T.levels[lvl], c = L.cell;
    return { tex: L.sTex, xf: [1 / (c * 256), (origin[0] / c + 0.5) / 256, (origin[2] / c + 0.5) / 256, HREF_SLOPE * origin[2] - origin[1]] };
  };
  // height lookup data for other shaders (particles): level 1 texture + mapping uniforms
  T.heightBinding = function (origin, lvl = 1) {
    const L = T.levels[lvl], c = L.cell;
    return { tex: L.hTex, xf: [1 / c, origin[0] / c, origin[2] / c, HREF_SLOPE * origin[2] - origin[1]] };
  };
  // ---- every level made again around a new place (another mountain: the course was re-seeded; or the skier was set down far away), a
  // little at a time: T.rebuild starts it, T.rebuildStep(ms) carries on for about that long and says whether it is finished. Coarse levels
  // first and each one whole before the next (the finer ones read them toward the sun): what T.update(x, z, true) does in one go, to the
  // last texel. Until it is finished the levels are not fit to be seen (App.swap keeps the picture covered) and T.update leaves them alone;
  // a forced T.update takes over and does it all at once.
  let job = null;
  T.rebuild = function (camX, camZ) { for (const L of T.levels) L.valid = false; job = { x: camX, z: camZ, l: T.LEVELS - 1, row: -1 }; };
  T.rebuilding = () => !!job;
  T.rebuildStep = function (ms = 1e9) {
    const t0 = performance.now(), B = 16;       // rows at a time: first the heights of the whole level, then its slopes, shade and horizon
    while (job) {
      const L = T.levels[job.l], c = L.cell;
      if (job.row < 0) { L.cx = Math.floor(job.x / (2 * c)) * 2; L.cz = Math.floor((job.z / c - T.BIAS) / 2) * 2; L.valid = true; job.row = 0; }
      const x0 = L.cx - 128, za = L.cz - 128 + job.row % N, zb = za + B - 1;
      if (job.row < N) genHeights(L, x0, x0 + N - 1, za, zb); else uploadRect(L, x0, x0 + N - 1, za, zb);
      job.row += B;
      if (job.row >= 2 * N) { job.row = -1; if (--job.l < 0) job = null; }
      if (performance.now() - t0 >= ms) break;
    }
    return !job;
  };
  { const update = T.update; T.update = function (camX, camZ, force) { if (job) { if (!force) return 0; job = null; } return update(camX, camZ, force); }; }
  return T;
})();

